const fs=require('fs');
const assert=require('assert');
const bill=fs.readFileSync('app/api/purchase-bill/route.ts','utf8');
const data=fs.existsSync('app/api/data/route.ts');
const page=fs.readFileSync('app/page.tsx','utf8');
const purchases=fs.readFileSync('app/api/purchases/route.ts','utf8');
const profile=fs.readFileSync('app/api/profile/route.ts','utf8');
assert(data,'/api/data route exists');
const model=fs.readFileSync('lib/documents/bill-model.ts','utf8');
const moisture=fs.readFileSync('lib/documents/moisture.ts','utf8');
assert(bill.includes('billDeductions(')&&model.includes("import { moistureDisplay } from './moisture'"),'bills get their deductions from the shared model, which gets moisture from the shared display helper');
assert(moisture.includes('perKgRule ? num(row?.quality_deduct_amount) : stored'),'the deduction amount is the one the existing calculation applied (v2.7.3)');
assert(moisture.includes('percent = perKgRule ? stored : (stored > 0 && stored <= PERCENT_MAX ? stored : 0)'),'a percentage is only shown when the stored value can be one');
assert(moisture.includes('`Moisture Deduction (${percentText})`'),'the percentage is printed in the label, never as the amount');
assert(model.includes("if (m.percent > 0) rows.push([m.label, m.amount, 'include_moisture', true])")&&model.includes("else rows.push(['Quality Deduct', quality, 'include_quality_deduct', false])"),'under the rate-per-kg rule moisture and quality are one row, never both');
assert(!/rows\.push\(\['Moisture',/.test(model),'no bare rupee Moisture row remains');
assert(purchases.includes('Truck number is required for new purchase/sample entries.'),'new purchase/sample requires truck number');
assert(page.includes('function UserProfile')&&page.includes('Change Password'),'profile UI exists');
assert(profile.includes('current_password')&&profile.includes('New password must be at least 12 characters.'),'profile password change is validated');
assert(page.includes("REVERSED"),'reversed actions have UI restrictions');
console.log('PASS moisture percentage and deduction are displayed separately (v2.7.3)');
